import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {transform} from 'esbuild';

const assets='extensions/theme-extension/assets/';
for(const name of ['collectionLoading','collectionFilterPro','collectionPreviewStream','collectionFilters']){
  let source=await fs.readFile(assets+name+'.js','utf8');
  if(name==='collectionFilterPro'){
    const shared=(await fs.readFile('app/utils/priceBounds.js','utf8')).replace('export function','function');
    source=source.replace(/\/\* CFP_PRICE_BOUNDS_START \*\/[\s\S]*?\/\* CFP_PRICE_BOUNDS_END \*\//,
      '/* CFP_PRICE_BOUNDS_START */\n'+shared+'\n  /* CFP_PRICE_BOUNDS_END */');
    const manual=(await fs.readFile('app/utils/manualFacetValues.js','utf8')).replaceAll('export function','function');
    source=source.replace(/\/\* CFP_MANUAL_VALUES_START \*\/[\s\S]*?\/\* CFP_MANUAL_VALUES_END \*\//,
      '/* CFP_MANUAL_VALUES_START */\n'+manual+'\n  /* CFP_MANUAL_VALUES_END */');
    const facetKeys=(await fs.readFile('app/utils/facetNormalization.js','utf8')).split(/\r?\n/).slice(0,3).join('\n').replaceAll('export const','const');
    source=source.replace(/\/\* CFP_FACET_KEYS_START \*\/[\s\S]*?\/\* CFP_FACET_KEYS_END \*\//,
      '/* CFP_FACET_KEYS_START */\n'+facetKeys+'\n  /* CFP_FACET_KEYS_END */');
    await fs.writeFile(assets+name+'.js',source);
  }
  const hash=createHash('sha256').update(source.replace(/\r\n/g,'\n')).digest('hex');
  const result=await transform(source,{minify:true,target:'es2020',legalComments:'none',charset:'utf8'});
  const output='// Generated by scripts/build-storefront-assets.mjs; source-sha256:'+hash+'\n'+result.code;
  await fs.writeFile(assets+name+'.min.js',output);
  if(name==='collectionLoading')await fs.writeFile('extensions/theme-extension/snippets/collection_loading_start.liquid','<script>'+output+'</script>\n');
  if(name==='collectionPreviewStream')await fs.writeFile('extensions/theme-extension/snippets/collection_stream_reader.liquid','<script>'+output+'</script>\n');
  if(name==='collectionFilters')await fs.writeFile('extensions/theme-extension/snippets/collection_filters_start.liquid','<script>'+output+'</script>\n');
  console.log(name+': '+Buffer.byteLength(source)+' -> '+Buffer.byteLength(output)+' bytes');
}
