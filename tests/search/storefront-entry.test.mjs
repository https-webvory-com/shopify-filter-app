import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import vm from 'node:vm';
import {createHash} from 'node:crypto';
import {transform} from 'esbuild';

const base='extensions/theme-extension/';
const entry=await fs.readFile(base+'assets/collectionWidget.js','utf8');
function fixture({present=false,readyState='loading',runtimeUrl}={}){
 const scripts=[],window={},listeners={};let block=present,callback,disconnected=false;
 const document={readyState,currentScript:{src:'https://cdn.shopify.com/extensions/version/assets/collectionWidget.js',dataset:runtimeUrl?{cfpRuntime:runtimeUrl}:{}},
  documentElement:{},head:{append:script=>scripts.push(script)},
  querySelector:selector=>selector.includes('#cfp-sidebar')?(block?{}:null):scripts.find(s=>s.dataset.cfpWidgetRuntime==='')||null,
  createElement:()=>({dataset:{},remove(){scripts.splice(scripts.indexOf(this),1);}}),
  addEventListener:(name,fn)=>listeners[name]=fn};
 const context={window,document,URL,MutationObserver:class{constructor(fn){callback=fn;}observe(){}disconnect(){disconnected=true;}}};
 const run=()=>vm.runInNewContext(entry,context);run();
 return {window,scripts,run,addBlock:()=>{block=true;callback?.();},domReady:()=>listeners.DOMContentLoaded?.(),disconnected:()=>disconnected};
}
test('widget waits for its app block and duplicate entry points load one version-scoped CDN runtime',()=>{
 const f=fixture();assert.equal(f.scripts.length,0);f.run();f.addBlock();f.run();
 assert.equal(f.scripts.length,1);assert.equal(f.scripts[0].src,'https://cdn.shopify.com/extensions/version/assets/collectionFilterPro.min.js');
 assert.equal(f.scripts[0].async,true);assert.equal(f.disconnected(),true);
});
test('explicit Liquid asset URLs retain their version and a CDN error permits retry',()=>{
 const url='https://cdn.shopify.com/extensions/version/assets/collectionFilterPro.min.js?v=123';
 const f=fixture({present:true,runtimeUrl:url});assert.equal(f.scripts[0].src,url);
 f.scripts[0].onerror();assert.equal(f.scripts.length,0);f.run();assert.equal(f.scripts.length,1);
 f.window._cfpRendererLoaded=true;f.run();assert.equal(f.scripts.length,1);
});
test('pages without an app block download no full widget and clean up their observer',()=>{
 const f=fixture();f.domReady();assert.equal(f.scripts.length,0);assert.equal(f.disconnected(),true);assert.equal(f.window._cfpWidgetEntryLoaded,false);
 const late=fixture({readyState:'complete'});assert.equal(late.scripts.length,0);assert.equal(late.window._cfpWidgetEntryLoaded,false);
});

test('search and collection blocks use the versioned Liquid runtime URL without a malformed timestamp suffix',async()=>{
 for(const name of ['snippets/collectionFilterPro.liquid','blocks/collection_loading.liquid']){
  const liquid=await fs.readFile(base+name,'utf8');
  assert.ok(liquid.includes('data-cfp-runtime="{{ \'collectionFilterPro.min.js\' | asset_url }}"'),name);
 }
});
test('registered extension JavaScript entry points remain below the 10000-byte budget',async()=>{
 for(const name of ['collection_filter_pro','collection_loading']){
  const block=await fs.readFile(base+'blocks/'+name+'.liquid','utf8');
  const schema=JSON.parse(block.split('{% schema %}')[1].split('{% endschema %}')[0]);
  if(!schema.javascript){
   assert.equal(name,'collection_loading');
   assert.ok(block.includes("{{ 'collectionLoading.min.js' | asset_url | preload_tag: as: 'script', fetchpriority: 'high' }}"));
   assert.ok(block.includes("<script src=\"{{ 'collectionLoading.min.js' | asset_url }}\""));
   continue;
  }
  const source=await fs.readFile(base+'assets/'+schema.javascript);
  assert.ok(source.length<10000,schema.javascript+' exceeds the app entry budget');
 }
});
test('published minified assets are generated from current source and inline loader matches the external loader',async()=>{
 for(const name of ['collectionLoading','collectionFilterPro','collectionPreviewStream','collectionFilters']){
  const source=await fs.readFile(base+'assets/'+name+'.js','utf8');
  const hash=createHash('sha256').update(source.replace(/\r\n/g,'\n')).digest('hex');
  const result=await transform(source,{minify:true,target:'es2020',legalComments:'none',charset:'utf8'});
  const expected='// Generated by scripts/build-storefront-assets.mjs; source-sha256:'+hash+'\n'+result.code;
  assert.equal(await fs.readFile(base+'assets/'+name+'.min.js','utf8'),expected);
  if(name==='collectionLoading')assert.equal(await fs.readFile(base+'snippets/collection_loading_start.liquid','utf8'),'<script>'+expected+'</script>\n');
  if(name==='collectionPreviewStream')assert.equal(await fs.readFile(base+'snippets/collection_stream_reader.liquid','utf8'),'<script>'+expected+'</script>\n');
  if(name==='collectionFilters')assert.equal(await fs.readFile(base+'snippets/collection_filters_start.liquid','utf8'),'<script>'+expected+'</script>\n');
 }
});
