window.runPinningChecks = async () => {
  const checks = [];
  const check = (name, pass) => { checks.push({ name, pass }); if (!pass) throw Error(name); };
  const wait = async fn => { for (let i = 0; i < 80; i++) { if (await fn()) return; await new Promise(r => setTimeout(r, 100)); } throw Error('UI did not settle'); };
  const pause = () => new Promise(r => setTimeout(r, 100));
  const click = text => [...document.querySelectorAll('button')].find(b => b.textContent.trim() === text).click();
  const cards = () => [...document.querySelectorAll('.product-search-card')];
  const pinBoxes = () => [...document.querySelectorAll('input[type=checkbox]')].slice(3);
  const order = () => pinBoxes().map(x => x.closest('[draggable=true]')?.innerText.split('\n').at(-1));
  await wait(() => cards().length === 9);
  check('picker contains only target-query products', cards().every(x => x.innerText.includes('Green')));
  click('Next'); await wait(() => cards().length === 3);
  check('matching products paginate', cards()[0].innerText.includes('Green Dress 10'));
  for (const title of ['Green Dress 10', 'Green Dress 11', 'Green Dress 12']) {
    await wait(() => cards().some(x => x.innerText.includes(title)));
    cards().find(x => x.innerText.includes(title)).querySelector('button').click();
    await wait(() => order().includes(title));
    await pause();
  }
  await wait(() => cards().length === 9);
  check('pinning last-page products returns to available matches', cards().every(x => !/Green Dress 1[012]\b/.test(x.innerText)));
  check('pins preserve click order', order().join('|') === 'Green Dress 10|Green Dress 11|Green Dress 12');
  pinBoxes()[0].click(); await pause(); pinBoxes()[1].click(); await pause();
  click('Move selected items to bottom'); await pause();
  check('move selected group preserves its relative order', order().join('|') === 'Green Dress 12|Green Dress 10|Green Dress 11');
  const dt = new DataTransfer();
  pinBoxes()[1].closest('[draggable=true]').dispatchEvent(new DragEvent('dragstart', { bubbles: true, dataTransfer: dt }));
  pinBoxes()[0].closest('[draggable=true]').dispatchEvent(new DragEvent('drop', { bubbles: true, dataTransfer: dt }));
  await pause();
  check('drag selected group into position', order().join('|') === 'Green Dress 10|Green Dress 11|Green Dress 12');
  const input = document.querySelector('[aria-label="Search products by Title"]');
  const setInput = value => { Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, value); input.dispatchEvent(new Event('input', { bubbles: true })); };
  setInput('Red'); await wait(() => document.body.innerText.includes('No matching products found.'));
  check('title search cannot broaden beyond target query', cards().length === 0);
  setInput(''); await wait(() => cards().length === 9);
  [...document.querySelectorAll('input[type=checkbox]')][2].click(); await pause();
  click('Save'); await wait(() => pinBoxes().length === 3 && document.querySelector('[aria-label="Search products by Title"]').value === '');
  let saved;
  await wait(async () => { saved = await (await fetch('/state')).json(); return saved.applyToSearchType === 'instant' && saved.products.length === 3; });
  check('save persists pin order', saved.products.map(p => p.title).join('|') === 'Green Dress 10|Green Dress 11|Green Dress 12');
  check('save persists instant-only scope', saved.applyToSearchType === 'instant');
  pinBoxes()[0].closest('[draggable=true]').querySelector('button').click();
  await wait(() => pinBoxes().length === 2);
  check('unpin removes exactly one product', order().join('|') === 'Green Dress 11|Green Dress 12');
  click('Clear pinned list'); await wait(() => pinBoxes().length === 0);
  check('clear leaves matching catalog usable', !document.body.innerText.includes('Green Dress 12\nPos:'));
  check('no browser errors', window.browserErrors.length === 0);
  return { checks, errors: window.browserErrors };
};
